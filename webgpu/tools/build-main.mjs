// Regenerates webgpu/js/main.js from the WebGL game's js/main.js, so game logic stays shared.
// Only the renderer setup, the post-processing chain and a few hooks are swapped. Every anchor must match or the build fails.
// Usage: node webgpu/tools/build-main.mjs
import fs from 'node:fs';
const root = new URL('../../', import.meta.url);
let s = fs.readFileSync(new URL('js/main.js', root), 'utf8');
const rep = (a, b, all = false) => { if (!s.includes(a)) throw new Error('anchor missing: ' + a.slice(0, 80)); s = all ? s.split(a).join(b) : s.replace(a, b); };
const cut = (a, b, ins) => { const i = s.indexOf(a), j = s.indexOf(b, i); if (i < 0 || j < 0) throw new Error('block missing: ' + a.slice(0, 60)); s = s.slice(0, i) + ins + s.slice(j + b.length); };

// imports: shared modules from ../../js/, renderer-specific ones from this folder
s = s.replace(/^import .*from 'three\/addons\/postprocessing\/.*$\n/gm, '');
s = s.replace(/from '\.\/(?!(gfx|scene|vfx)\.js)([\w]+\.js)'/g, "from '../../js/$2'");
rep("import * as THREE from 'three';", `import * as THREE from 'three';
import { createPost } from './post.js';
import { upgradeShared, upgradeScene, tickNodeMats } from './nodeMats.js';
import { attachPendingReflectors } from './gfx.js';
import { initGpuExtras, updateGpuExtras, setGpuQuality } from './extras.js';
import { BACKEND } from './scene.js';`);
rep('const renderer = createRenderer();', 'const renderer = await createRenderer();');
cut('const composer = new EffectComposer(renderer', 'if (smaa) composer.addPass(smaa);',
  `const post = createPost(renderer, scene, camera);
const { gtao, GRADE } = post;
const smaa = null;   // WebGPU: AA comes from the renderer / post pipeline`);
rep('const { nodes, monsters, pickables, ground, buildings } = createWorld(scene);', `const { nodes, monsters, pickables, ground, buildings } = createWorld(scene);
attachPendingReflectors(scene); upgradeShared(); upgradeScene(scene);
initGpuExtras({ scene, camera, renderer, dirLight, lightsRef });`);
rep(`  composer.setPixelRatio(renderer.getPixelRatio());
  composer.setSize(window.innerWidth, window.innerHeight);
`, '');
rep("gradePass.uniforms.sat.value = gfx.quality === 'low' ? 1.12 : 1.45;", "GRADE.sat.value = gfx.quality === 'low' ? 1.12 : 2.0; post.needsUpdate(); setGpuQuality(gfx.quality); post.setQuality(gfx.quality);");
rep('renderer.setPixelRatio(pr); composer.setPixelRatio(pr);', 'renderer.setPixelRatio(pr);');
// WebGPU post grades differently (no extra darkening), so the root fog lift washes it out: smaller lift here
rep('const HIGH_FOG_LIFT = [2.8, 3.6, 5.2];', 'const HIGH_FOG_LIFT = [2.0, 2.4, 3.1];');
// WebGPU has its own TSL weather (stage 5); the WebGL drizzle's ShaderMaterial can't run on WebGPURenderer
rep("import { updateDrizzle } from '../../js/weather.js';\n", '');
rep('\n  updateDrizzle(scene, camera, dt, gfx.quality, inCave(pm.mesh.position.x, pm.mesh.position.z));', '');
rep('const U = gradePass.uniforms;', 'const U = GRADE;');
rep(`  composer.setSize(window.innerWidth, window.innerHeight);
  bloom.resolution.set(window.innerWidth, window.innerHeight);
`, '');
rep('composer.render();', 'post.render();');
rep('  frame++;', `  frame++;
  if (frame % 20 === 3) upgradeScene(scene);
  tickNodeMats(); updateGpuExtras(dt, now, pm.mesh.position, gfx.quality);`);
fs.writeFileSync(new URL('webgpu/js/main.js', root), '// GENERATED by webgpu/tools/build-main.mjs from js/main.js. Do not edit by hand.\n' + s);
console.log('webgpu/js/main.js written,', s.length, 'chars');
